"use server";

import { revalidatePath } from "next/cache";
import { z } from "zod";
import { requireMember } from "@/shared/lib/member";
import { codeFromDbError, fail, ok, okVoid, type Result } from "@/shared/lib/result";
import type { SalesRecord } from "@/features/sales/totals";

const PATH = "/more/sales";

const saleInput = z.object({
  type: z.enum(["현금", "카드"]),
  amount: z.number().int().positive().max(100_000_000),
  name: z.string().trim().max(100),
  date: z.iso.datetime(),
});

// 화면이 고른 날짜 + 시각(휴대폰 시간대)을 ISO 로 보낸다. 미래만 막는다(시계 차이 5분 허용).
function isFuture(iso: string) {
  return new Date(iso).getTime() > Date.now() + 5 * 60_000;
}

export async function addSale(raw: { type: string; amount: number; name: string; date: string }): Promise<Result> {
  const auth = await requireMember();
  if (!auth.ok) return auth;
  const input = saleInput.safeParse(raw);
  if (!input.success) return fail(raw.amount > 0 ? "INVALID_INPUT" : "SALES_AMOUNT");
  if (isFuture(input.data.date)) return fail("SALES_FUTURE");

  const { type, amount, name, date } = input.data;
  const { error } = await auth.supabase
    .from("sales_record")
    .insert({ pay_type: type, amount, final_amount: amount, name, sold_at: date });
  if (error) return fail(codeFromDbError(error));
  revalidatePath(PATH);
  return okVoid();
}

export async function updateSale(
  id: number,
  raw: { type: string; amount: number; name: string; date: string },
): Promise<Result> {
  const auth = await requireMember();
  if (!auth.ok) return auth;
  const sid = z.number().int().positive().safeParse(id);
  const input = saleInput.safeParse(raw);
  if (!sid.success) return fail("INVALID_INPUT");
  if (!input.success) return fail(raw.amount > 0 ? "INVALID_INPUT" : "SALES_AMOUNT");
  if (isFuture(input.data.date)) return fail("SALES_FUTURE");

  const { type, amount, name, date } = input.data;
  // 옛 앱(buildUpdatePatch)처럼 고치면 실수령 = 금액이 된다. 옛 카드 행의 수수료 뺀 값도 이때 사라진다.
  const { data, error } = await auth.supabase
    .from("sales_record")
    .update({ pay_type: type, amount, final_amount: amount, name, sold_at: date })
    .eq("id", sid.data)
    .select("id")
    .maybeSingle();
  if (error) return fail(codeFromDbError(error));
  if (!data) return fail("SALES_NOT_FOUND");
  revalidatePath(PATH);
  return okVoid();
}

// 지운 행을 돌려준다. 화면의 [실행취소]가 그 값으로 restoreSale 을 부른다.
export async function deleteSale(id: number): Promise<Result<SalesRecord>> {
  const auth = await requireMember();
  if (!auth.ok) return auth;
  const sid = z.number().int().positive().safeParse(id);
  if (!sid.success) return fail("INVALID_INPUT");

  const { data, error } = await auth.supabase
    .from("sales_record")
    .delete()
    .eq("id", sid.data)
    .select("id, sold_at, pay_type, amount, final_amount, name")
    .maybeSingle();
  if (error) return fail(codeFromDbError(error));
  if (!data) return fail("SALES_NOT_FOUND");
  revalidatePath(PATH);
  return ok({
    id: data.id,
    type: data.pay_type,
    original: data.amount,
    final: data.final_amount,
    name: data.name,
    date: data.sold_at,
  });
}

// 같은 id 로 다시 넣는다(id 는 generated by default 라 직접 넣을 수 있다). 두 번 누르면 DUPLICATE.
export async function restoreSale(rec: SalesRecord): Promise<Result> {
  const auth = await requireMember();
  if (!auth.ok) return auth;
  const input = z
    .object({
      id: z.number().int().positive(),
      type: z.enum(["현금", "카드"]),
      original: z.number().int().positive(),
      final: z.number().int().nonnegative(),
      name: z.string().max(100),
      date: z.iso.datetime({ offset: true }),
    })
    .safeParse(rec);
  if (!input.success) return fail("INVALID_INPUT");

  const r = input.data;
  const { error } = await auth.supabase
    .from("sales_record")
    .insert({ id: r.id, pay_type: r.type, amount: r.original, final_amount: r.final, name: r.name, sold_at: r.date });
  if (error) return fail(codeFromDbError(error));
  revalidatePath(PATH);
  return okVoid();
}
