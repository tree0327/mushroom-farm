-- 4. 화면용 함수 (security invoker = RLS 가 그대로 걸린다)
-- ─────────────────────────────────────────────

-- 하루 저장. p_values = [{field_id, room_id(null=농장), num_value, option_id, text_value}] — 셋 다 비면 그 칸을 지운다.
create or replace function public.mf_save_day(p_log_date date, p_memo text, p_values jsonb)
returns void
language plpgsql
set search_path = ''
as $$
declare
  r jsonb;
  v_field bigint;
  v_room bigint;
  v_num numeric;
  v_option bigint;
  v_text text;
  v_memo text := coalesce(btrim(p_memo), '');
begin
  if v_memo = '' then
    delete from public.mf_day where log_date = p_log_date;
  else
    insert into public.mf_day (log_date, memo) values (p_log_date, v_memo)
    on conflict (log_date) do update set memo = excluded.memo;
  end if;

  for r in select * from jsonb_array_elements(coalesce(p_values, '[]'::jsonb)) loop
    v_field := (r ->> 'field_id')::bigint;
    v_room := (r ->> 'room_id')::bigint;
    v_num := (r ->> 'num_value')::numeric;
    v_option := (r ->> 'option_id')::bigint;
    v_text := nullif(btrim(r ->> 'text_value'), '');
    if v_num is null and v_option is null and v_text is null then
      delete from public.mf_value
      where log_date = p_log_date and field_id = v_field and room_id is not distinct from v_room;
    else
      insert into public.mf_value (log_date, field_id, room_id, num_value, option_id, text_value)
      values (p_log_date, v_field, v_room, v_num, v_option, v_text)
      on conflict on constraint mf_value_log_date_field_id_room_id_uk do update set
        num_value = excluded.num_value,
        option_id = excluded.option_id,
        text_value = excluded.text_value;
    end if;
  end loop;
end;
$$;

create or replace function public.mf_delete_day(p_log_date date)
returns void
language sql
set search_path = ''
as $$
  delete from public.mf_value where log_date = p_log_date;
  delete from public.mf_day where log_date = p_log_date;
$$;

-- 기간의 하루별 합계. totals = {"<field_id>": {"sum", "min", "max", "n", "opts": {"<option_id>": 횟수}}}
-- 호실 항목은 그날 모든 호실을 합친 값(평균은 화면이 sum ÷ n 으로 낸다). 1년이면 최대 366행.
create or replace function public.mf_farm_days(p_from date, p_to date)
returns table (log_date date, has_memo boolean, totals jsonb)
language sql
stable
set search_path = ''
as $$
  with v as (
    select x.log_date, x.field_id, x.num_value, x.option_id
    from public.mf_value x
    where x.log_date between p_from and p_to
  ),
  opt as (
    select o.log_date, o.field_id, jsonb_object_agg(o.option_id::text, o.c) as opts
    from (select log_date, field_id, option_id, count(*) as c from v where option_id is not null group by 1, 2, 3) o
    group by o.log_date, o.field_id
  ),
  per_field as (
    select v.log_date, v.field_id, sum(v.num_value) as s, min(v.num_value) as mn, max(v.num_value) as mx, count(*) as n
    from v
    group by v.log_date, v.field_id
  ),
  per_day as (
    select p.log_date,
           jsonb_object_agg(
             p.field_id::text,
             jsonb_strip_nulls(jsonb_build_object('sum', p.s, 'min', p.mn, 'max', p.mx, 'n', p.n, 'opts', o.opts))
           ) as totals
    from per_field p
    left join opt o on o.log_date = p.log_date and o.field_id = p.field_id
    group by p.log_date
  ),
  dates as (
    select log_date from per_day
    union
    select d.log_date from public.mf_day d where d.log_date between p_from and p_to
  )
  select x.log_date, md.log_date is not null, coalesce(pd.totals, '{}'::jsonb)
  from dates x
  left join per_day pd on pd.log_date = x.log_date
  left join public.mf_day md on md.log_date = x.log_date
  order by x.log_date;
$$;

-- 기간의 호실·항목별 합계(숫자 항목만)
create or replace function public.mf_room_totals(p_from date, p_to date)
returns table (room_id bigint, field_id bigint, sum_value numeric, value_count bigint)
language sql
stable
set search_path = ''
as $$
  select v.room_id, v.field_id, sum(v.num_value), count(*)
