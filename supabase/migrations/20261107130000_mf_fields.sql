-- 2. 규칙 트리거
-- ─────────────────────────────────────────────

-- 기본 항목(role)은 지우거나 범위·종류·역할을 바꿀 수 없고, 값이 쌓인 항목은 범위(scope)·종류를 바꿀 수 없다.
create or replace function app.mf_field_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.role is not null then
      raise exception '기본 항목은 지울 수 없다' using errcode = 'check_violation';
    end if;
    return old;
  end if;
  if new.role is distinct from old.role then
    raise exception '항목 역할은 바꿀 수 없다' using errcode = 'check_violation';
  end if;
  if (new.scope <> old.scope or new.value_type <> old.value_type)
     and (old.role is not null or exists (select 1 from public.mf_value v where v.field_id = old.id)) then
    raise exception '값이 있거나 기본 항목이면 범위·종류를 바꿀 수 없다' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;
create trigger mf_field_guard_tg before update or delete on public.mf_field
  for each row execute function app.mf_field_guard();

-- 값이 항목 정의(농장/호실, 종류, 입력 범위, 보기 소속)에 맞는지
create or replace function app.mf_value_check()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  f record;
begin
  select scope, value_type, min_value, max_value into f from public.mf_field where id = new.field_id;
  if not found then
    raise exception '없는 항목' using errcode = 'foreign_key_violation';
  end if;
  if (f.scope = 'farm') <> (new.room_id is null) then
    raise exception '농장 항목은 호실 없이, 호실 항목은 호실과 함께' using errcode = 'check_violation';
  end if;
  if f.value_type in ('int', 'decimal') then
    if new.num_value is null
       or (f.value_type = 'int' and new.num_value <> trunc(new.num_value))
       or new.num_value < f.min_value
       or new.num_value > f.max_value then
      raise exception '숫자 값이 항목 정의와 맞지 않다' using errcode = 'check_violation';
    end if;
  elsif f.value_type = 'choice' then
    if new.option_id is null
       or not exists (select 1 from public.mf_field_option o where o.id = new.option_id and o.field_id = new.field_id) then
      raise exception '이 항목의 보기가 아니다' using errcode = 'check_violation';
    end if;
  elsif new.text_value is null then
    raise exception '글 항목에는 글만' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;
create trigger mf_value_check_tg before insert or update on public.mf_value
  for each row execute function app.mf_value_check();

revoke execute on function app.mf_field_guard(), app.mf_value_check() from public, anon;

