-- 2. 판정 함수 (app 스키마 — 유일한 기준)
-- 시각이 드는 함수는 p_at 을 받는다. 시험에서 시각을 넣어 돌리기 위해서다.
-- ─────────────────────────────────────────────

-- 로그인한 사람의 member.id. 회원이 아니면 null.
-- security definer: member 표 RLS 가 이 함수를 부르므로 RLS 를 건너뛰어야 돌고 돌지 않는다.
create or replace function app.current_member_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select m.id from public.member m where m.user_id = (select auth.uid());
$$;

create or replace function app.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select m.is_admin from public.member m where m.user_id = (select auth.uid())), false);
$$;

create or replace function app.kst_date(p_at timestamptz default now())
returns date
language sql
stable
set search_path = ''
as $$
  select (p_at at time zone 'Asia/Seoul')::date;
$$;

-- 쉬는 날: 주말(설정이 켜져 있을 때) 또는 관리자가 더한 날
create or replace function app.is_rest_day(p_date date)
returns boolean
language sql
stable
set search_path = ''
as $$
  select
    (extract(isodow from p_date) in (6, 7)
       and coalesce((select s.is_weekend_rest from public.app_setting s where s.id = 1), true))
    or exists (select 1 from public.rest_day r where r.rest_date = p_date);
$$;

-- 일기 쓰기·고치기: 그날(한국 날짜) 안, 쉬는 날이 아닐 때
create or replace function app.can_write_diary(p_entry_date date, p_at timestamptz default now())
returns boolean
language sql
stable
set search_path = ''
as $$
  select p_entry_date = app.kst_date(p_at) and not app.is_rest_day(p_entry_date);
$$;

-- 상대 일기 공개: 다음날 한국 시각 9시부터
create or replace function app.is_diary_revealed(p_entry_date date, p_at timestamptz default now())
returns boolean
language sql
stable
set search_path = ''
as $$
  select p_at >= (((p_entry_date + 1)::timestamp + time '09:00') at time zone 'Asia/Seoul');
$$;

-- 답장 쓰기·고치기: 공개된 날(다음날) 9시부터 자정 전까지
create or replace function app.can_reply(p_entry_date date, p_at timestamptz default now())
returns boolean
language sql
stable
set search_path = ''
as $$
  select app.is_diary_revealed(p_entry_date, p_at) and app.kst_date(p_at) = p_entry_date + 1;
$$;

-- 쿠폰 상태 바꾸기 검사. 받은 사람만 사용, 준 사람만 완료, 기간 지나면 사용 불가, 다른 칸은 못 바꾼다.
create or replace function app.check_coupon_update()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  me bigint := app.current_member_id();
begin
  if new.giver_id <> old.giver_id or new.receiver_id <> old.receiver_id
     or new.title <> old.title or new.body <> old.body
     or new.expires_on is distinct from old.expires_on then
    raise exception 'COUPON_LOCKED_FIELDS';
  end if;
  if new.status = old.status then
    raise exception 'COUPON_ALREADY_CHANGED';
  end if;
  if old.status = 'issued' and new.status = 'used' then
    if me is distinct from old.receiver_id then raise exception 'COUPON_NOT_RECEIVER'; end if;
    if old.expires_on is not null and old.expires_on < app.kst_date() then raise exception 'COUPON_EXPIRED'; end if;
    new.used_at := now();
    new.done_at := null;
  elsif old.status = 'used' and new.status = 'done' then
    if me is distinct from old.giver_id then raise exception 'COUPON_NOT_GIVER'; end if;
    new.used_at := old.used_at;
    new.done_at := now();
  else
    raise exception 'COUPON_ALREADY_CHANGED';
  end if;
  return new;
end;
$$;

create trigger wish_coupon_status_tg before update on public.wish_coupon
  for each row execute function app.check_coupon_update();

