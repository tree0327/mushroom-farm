-- 해답의 책 펼치기: 무작위 문구 하나를 고르고 기록을 남긴다(한 번에).
create or replace function public.draw_answer(p_worry text)
returns table (draw_id bigint, phrase_id bigint, body text, is_default boolean, author_id uuid)
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_phrase public.answer_phrase%rowtype;
  v_draw bigint;
begin
  select * into v_phrase from public.answer_phrase order by random() limit 1;
  if not found then
    raise exception 'ANSWER_EMPTY';
  end if;
  insert into public.answer_draw (member_id, phrase_id, worry)
  values (app.current_member_id(), v_phrase.id, coalesce(btrim(p_worry), ''))
  returning id into v_draw;
  return query select v_draw, v_phrase.id, v_phrase.body, v_phrase.is_default, v_phrase.created_by;
end;
$$;

