-- 하루 저장(한 번에). 칸이 모두 비면 그 행을 지운다. p_rooms = [{room_id, good_kg, defect_kg, temperature_c, humidity_pct}]
create or replace function public.save_day(
  p_log_date date,
  p_bottled_count integer,
  p_inoculated_count integer,
  p_contaminated_count integer,
  p_memo text,
  p_rooms jsonb
)
returns void
language plpgsql
volatile
set search_path = ''
as $$
declare
  r jsonb;
  v_room_id bigint;
  v_good numeric;
  v_defect numeric;
  v_temp numeric;
  v_hum smallint;
  v_memo text := coalesce(btrim(p_memo), '');
begin
  if p_bottled_count is null and p_inoculated_count is null and p_contaminated_count is null and v_memo = '' then
    delete from public.daily_log where log_date = p_log_date;
  else
    insert into public.daily_log (log_date, bottled_count, inoculated_count, contaminated_count, memo)
    values (p_log_date, p_bottled_count, p_inoculated_count, p_contaminated_count, v_memo)
    on conflict (log_date) do update set
      bottled_count = excluded.bottled_count,
      inoculated_count = excluded.inoculated_count,
      contaminated_count = excluded.contaminated_count,
      memo = excluded.memo;
  end if;

  for r in select * from jsonb_array_elements(coalesce(p_rooms, '[]'::jsonb)) loop
    v_room_id := (r ->> 'room_id')::bigint;
    v_good := (r ->> 'good_kg')::numeric;
    v_defect := (r ->> 'defect_kg')::numeric;
    v_temp := (r ->> 'temperature_c')::numeric;
    v_hum := (r ->> 'humidity_pct')::smallint;
    if v_good is null and v_defect is null and v_temp is null and v_hum is null then
      delete from public.room_log where log_date = p_log_date and room_id = v_room_id;
    else
      insert into public.room_log (log_date, room_id, good_kg, defect_kg, temperature_c, humidity_pct)
      values (p_log_date, v_room_id, v_good, v_defect, v_temp, v_hum)
      on conflict (log_date, room_id) do update set
        good_kg = excluded.good_kg,
        defect_kg = excluded.defect_kg,
        temperature_c = excluded.temperature_c,
        humidity_pct = excluded.humidity_pct;
    end if;
  end loop;
end;
$$;

create or replace function public.delete_day(p_log_date date)
returns void
language sql
volatile
set search_path = ''
as $$
  delete from public.room_log where log_date = p_log_date;
  delete from public.daily_log where log_date = p_log_date;
$$;

-- 날짜별 합계(호실 수확을 더한다). 기록이 하나라도 있는 날만. 목록 달력·분석이 쓴다.
-- 1년 + 직전 1년이라도 731행이라 Data API 한 번(최대 1000행)에 들어온다.
create or replace function public.farm_days(p_from date, p_to date)
returns table (
  log_date date,
  bottled_count bigint,
  inoculated_count bigint,
  contaminated_count bigint,
  good_kg numeric,
  defect_kg numeric,
  has_memo boolean
)
language sql
stable
set search_path = ''
as $$
  with dates as (
    select d.log_date from public.daily_log d where d.log_date between p_from and p_to
    union
    select r.log_date from public.room_log r where r.log_date between p_from and p_to
  ),
  rooms as (
    select r.log_date, sum(r.good_kg) as good_kg, sum(r.defect_kg) as defect_kg
    from public.room_log r
    where r.log_date between p_from and p_to
    group by r.log_date
  )
  select x.log_date, d.bottled_count, d.inoculated_count, d.contaminated_count,
         rm.good_kg, rm.defect_kg, coalesce(d.memo, '') <> ''
  from dates x
  left join public.daily_log d on d.log_date = x.log_date
  left join rooms rm on rm.log_date = x.log_date
  order by x.log_date;
$$;

-- 호실별 수확 합계(안 쓰는 호실도 기록이 있으면 나온다)
create or replace function public.room_totals(p_from date, p_to date)
returns table (room_id bigint, name text, is_active boolean, good_kg numeric, defect_kg numeric)
language sql
stable
set search_path = ''
as $$
  select rm.id, rm.name, rm.is_active, sum(r.good_kg), sum(r.defect_kg)
  from public.room_log r
  join public.room rm on rm.id = r.room_id
  where r.log_date between p_from and p_to
  group by rm.id, rm.name, rm.is_active, rm.sort_order
  order by rm.sort_order, rm.id;
$$;

