-- 2. 회원 판정 (app 스키마)
-- 로그인한 구글 계정의 이메일(auth.users.email)로 member 를 찾는다.
-- security definer: auth.users 를 읽고, member RLS 가 이 함수를 불러도 돌고 돌지 않게.
-- ─────────────────────────────────────────────
create or replace function app.current_member_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select m.id
  from public.member m
  join auth.users u on lower(u.email) = m.email
  where u.id = (select auth.uid());
$$;

create or replace function app.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select m.is_admin
    from public.member m
    join auth.users u on lower(u.email) = m.email
    where u.id = (select auth.uid())
  ), false);
$$;

